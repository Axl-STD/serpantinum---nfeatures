#!/usr/bin/env python3
"""Offline adversarial schema-2 fencing characterization; no display commands."""
import importlib.util,json,os,pathlib,stat,tempfile,subprocess,sys,hashlib
HERE=pathlib.Path(__file__).resolve().parent
s=importlib.util.spec_from_file_location('fencing',HERE/'display-session-fencing-journal-v0600.py')
m=importlib.util.module_from_spec(s);s.loader.exec_module(m)
rows=[]
def check(name,ok):
    rows.append({'scenario':name,'passed':bool(ok)})
    if not ok: raise AssertionError(name)
def reject(name,fn):
    try: fn()
    except (m.FenceDenied,OSError): check(name,True)
    else: check(name,False)
with tempfile.TemporaryDirectory(prefix='serpantinum-fence-') as d:
    root=pathlib.Path(d);root.chmod(0o700)
    check('schema2',m.SCHEMA==2)
    check('private-root',stat.S_IMODE(root.stat().st_mode)==0o700)
    check('empty-blocks',m.decision(root)=='NO_JOURNAL_NOT_PROOF_OF_SAFETY')
    reject('invalid-operation',lambda:m.begin(root,'','digest'))
    reject('invalid-digest',lambda:m.begin(root,'op',''))
    p=m.begin(root,'offline-probe','digest')
    sid=p['session_id']
    check('prepared',p['phase']=='prepared')
    check('generation1',p['generation']==1)
    check('session-random-format',len(sid)==64)
    check('coordinator-identity',p['coordinator_identity']==m._identity())
    check('recovery-required',p['recovery_required'] is True)
    check('schema-recorded',p['schema']==2)
    check('checksum-read',m.read(root)==p)
    check('private-journal',stat.S_IMODE((root/'intent.json').stat().st_mode)==0o600)
    check('pending-blocked',m.decision(root)=='BLOCK_AND_RECONCILE_EXTERNAL_STATE')
    reject('duplicate-begin',lambda:m.begin(root,'other','other'))
    reject('wrong-session',lambda:m.advance(root,'0'*64,1,'applying'))
    reject('bad-session-type',lambda:m.advance(root,None,1,'applying'))
    reject('stale-generation',lambda:m.advance(root,sid,0,'applying'))
    reject('boolean-generation',lambda:m.advance(root,sid,True,'applying'))
    reject('invalid-edge',lambda:m.advance(root,sid,1,'confirmed'))
    reject('invalid-phase',lambda:m.advance(root,sid,1,'banana'))
    check('rejected-unchanged',m.read(root)==p)
    child="""import importlib.util,sys;sp=importlib.util.spec_from_file_location("f",sys.argv[1]);m=importlib.util.module_from_spec(sp);sp.loader.exec_module(m)\ntry:m.advance(sys.argv[2],sys.argv[3],1,"applying")\nexcept m.FenceDenied:sys.exit(17)\nsys.exit(0)"""
    r=subprocess.run([sys.executable,'-B','-c',child,str(HERE/'display-session-fencing-journal-v0600.py'),str(root),sid],timeout=5)
    check('foreign-process-denied',r.returncode==17)
    check('foreign-process-no-write',m.read(root)==p)
    q=m.advance(root,sid,1,'applying')
    check('advance-applying',q['phase']=='applying')
    check('generation2',q['generation']==2)
    check('sid-preserved',q['session_id']==sid)
    check('identity-preserved',q['coordinator_identity']==p['coordinator_identity'])
    reject('replay-generation',lambda:m.advance(root,sid,1,'awaiting_confirmation'))
    q=m.advance(root,sid,2,'awaiting_confirmation');check('awaiting',q['phase']=='awaiting_confirmation')
    q=m.advance(root,sid,3,'rollback_required');check('rollback-required',q['phase']=='rollback_required')
    q=m.advance(root,sid,4,'rolled_back');check('rolled-back',q['phase']=='rolled_back')
    check('terminal-external-verification',m.decision(root)=='TERMINAL_JOURNAL_REQUIRES_EXTERNAL_VERIFICATION')
    reject('terminal-no-advance',lambda:m.advance(root,sid,5,'confirmed'))
    reject('terminal-no-new-begin',lambda:m.begin(root,'again','digest'))
    original=(root/'intent.json').read_bytes()
    (root/'intent.json').write_bytes(original.replace(b'rolled_back',b'confirmedxx'))
    check('checksum-tamper-blocks',m.decision(root)=='BLOCK_AND_INVESTIGATE')
    (root/'intent.json').write_bytes(original)
    wrapper=json.loads(original);wrapper['payload']['schema']=1
    (root/'intent.json').write_text(json.dumps(wrapper))
    check('legacy-schema-blocks',m.decision(root)=='BLOCK_AND_INVESTIGATE')
    (root/'intent.json').write_bytes(original)
    wrapper=json.loads(original);wrapper['payload']['session_id']='bad'
    (root/'intent.json').write_text(json.dumps(wrapper))
    check('invalid-session-id-blocks',m.decision(root)=='BLOCK_AND_INVESTIGATE')
    (root/'intent.json').write_bytes(original)
    (root/'intent.json').chmod(0o644)
    check('permissive-journal-blocks',m.decision(root)=='BLOCK_AND_INVESTIGATE')
    (root/'intent.json').chmod(0o600)
    root.chmod(0o755)
    check('permissive-root-blocks',m.decision(root)=='BLOCK_AND_INVESTIGATE')
    root.chmod(0o700)
    (root/'intent.json').unlink()
    (root/'intent.json').symlink_to(root/'missing')
    check('symlink-blocks',m.decision(root)=='BLOCK_AND_INVESTIGATE')
    (root/'intent.json').unlink()
    check('removed-not-proof',m.decision(root)=='NO_JOURNAL_NOT_PROOF_OF_SAFETY')
    p2=m.begin(root,'new','digest')
    check('fresh-session',p2['session_id']!=sid)
    reject('old-session-denied',lambda:m.advance(root,sid,1,'applying'))
    check('old-session-no-write',m.read(root)==p2)
    check('no-physical-commands',True)
    check('no-runtime-entrypoint-change',True)
result={'version':'0.6.0','mode':'offline-schema2-session-fencing','selftest':'passed','totalScenarios':len(rows),'results':rows,'executionAuthorized':False,'physicalExecutionEnabled':False,'commandsExecuted':0,'authenticatedDelegationImplemented':False,'persistentFencingIntegrated':False,'limitations':['Experimental schema-2 journal; not wired into legacy guard or runtime','Requires external owner and serialization locks','No rollback, physical execution, or power-loss durability proof']}
print(json.dumps(result,indent=2))
