#!/usr/bin/env python3
"""Offline regression of supervisor admission. No systemd or Hyprland commands."""
import copy, importlib.util, json
from pathlib import Path
p=Path(__file__).with_name('display-physical-supervisor-admission-v0600.py')
s=importlib.util.spec_from_file_location('supervisor_admission',p)
m=importlib.util.module_from_spec(s);s.loader.exec_module(m)
r=dict(id='a'*64,boot_id='boot',target='eDP-1',topology='internal-only',plan_sha256='b'*64,deadline_boottime_ns=123456789,generation=3,execution_backend='physical',state='ARMED')
base=dict(name='eDP-1',description='AU Optronics',width=1920,height=1080,refreshRate=60.061,x=0,y=0,scale=1,transform=0,disabled=False,dpmsStatus=True)
snap=dict(transaction_id=r['id'],boot_id='boot',target='eDP-1',topology='internal-only',snapshot=[base],snapshot_sha256=m.digest([base]),identity={'instance':'lab_instance'})
receipt=dict(status='OBSERVED_SERVICE_ONLY',transaction_id=r['id'],transaction_digest=m.digest({k:r[k] for k in m.REQUIRED}))
inputs=[r,snap,receipt,[{'instance':'lab_instance'}],[copy.deepcopy(base)],dict(LoadState='loaded',ActiveState='active',Result='success')]
checks=[]
def check(name,change,expected):
    data=copy.deepcopy(inputs);change(data)
    out=m.evaluate(*data)
    assert out['decision']==expected,(name,out)
    assert out['physicalExecutionEnabled'] is False and out['executionAuthorized'] is False and out['watchdogPhysicalArmed'] is False and out['commandsExecuted']==0 and out['rollbackPhysicalVerified'] is False
    checks.append({'scenario':name,'passed':True})
check('baseline',lambda d:None,'READONLY_SUPERVISOR_EVIDENCE_CONSISTENT')
check('lab-receipt',lambda d:d[2].update(status='ARMED_LAB_ONLY'),'BLOCK_LAB_RECEIPT')
check('simulated-backend',lambda d:d[0].update(execution_backend='simulated'),'BLOCK_TRANSACTION')
check('unknown-backend',lambda d:d[0].update(execution_backend='unknown'),'BLOCK_TRANSACTION')
check('terminal-state',lambda d:d[0].update(state='ROLLED_BACK'),'BLOCK_TRANSACTION')
check('target',lambda d:d[0].update(target='DP-1'),'BLOCK_TARGET')
check('generation',lambda d:d[0].update(generation=-1),'BLOCK_TRANSACTION_SCHEMA')
check('deadline',lambda d:d[0].update(deadline_boottime_ns=0),'BLOCK_DEADLINE')
check('id',lambda d:d[0].update(id='bad'),'BLOCK_TRANSACTION_SCHEMA')
check('snapshot-identity',lambda d:d[1].update(transaction_id='other'),'BLOCK_SNAPSHOT_IDENTITY')
check('snapshot-digest',lambda d:d[1].update(snapshot_sha256='0'*64),'BLOCK_SNAPSHOT_DIGEST')
check('snapshot-topology',lambda d:d[1]['snapshot'][0].update(name='DP-1'),'BLOCK_SNAPSHOT_DIGEST')
check('receipt-digest',lambda d:d[2].update(transaction_digest='0'*64),'BLOCK_RECEIPT')
check('instance-ambiguous',lambda d:d[3].append({'instance':'other'}),'BLOCK_INSTANCE')
check('instance-drift',lambda d:d[3][0].update(instance='other'),'BLOCK_INSTANCE_DRIFT')
check('hotplug',lambda d:d[4].append(dict(base,name='DP-1')),'BLOCK_TOPOLOGY_DRIFT')
check('connector',lambda d:d[4][0].update(name='DP-1'),'BLOCK_TOPOLOGY_DRIFT')
check('resolution',lambda d:d[4][0].update(width=1280),'BLOCK_GEOMETRY_DRIFT')
check('scale',lambda d:d[4][0].update(scale=1.25),'BLOCK_GEOMETRY_DRIFT')
check('position',lambda d:d[4][0].update(x=10),'BLOCK_GEOMETRY_DRIFT')
check('panel',lambda d:d[4][0].update(description='different'),'BLOCK_GEOMETRY_DRIFT')
check('refresh-unknown',lambda d:d[4][0].update(refreshRate=75),'BLOCK_REFRESH')
check('refresh-candidate',lambda d:d[4][0].update(refreshRate=144.06),'READONLY_SUPERVISOR_EVIDENCE_CONSISTENT')
check('service-inactive',lambda d:d[5].update(ActiveState='inactive'),'BLOCK_SERVICE_NOT_ACTIVE')
check('service-failed',lambda d:d[5].update(Result='exit-code'),'BLOCK_SERVICE_FAILED')
check('service-not-loaded',lambda d:d[5].update(LoadState='not-found'),'BLOCK_SERVICE_NOT_ACTIVE')
check('malformed-instance',lambda d:d.__setitem__(3,None),'BLOCK_INSTANCE')
check('malformed-monitor',lambda d:d.__setitem__(4,None),'BLOCK_TOPOLOGY_DRIFT')
check('missing-receipt',lambda d:d.__setitem__(2,None),'BLOCK_SCHEMA')
check('missing-snapshot',lambda d:d.__setitem__(1,None),'BLOCK_SCHEMA')
print(json.dumps(dict(selftest='passed',totalScenarios=len(checks),results=checks,physicalExecutionEnabled=False,executionAuthorized=False,commandsExecuted=0,rollbackPhysicalVerified=False),indent=2))
